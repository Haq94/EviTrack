def bimodality_kurtosis_proxy(z_1d: np.ndarray) -> float:
    z = np.asarray(z_1d, dtype=float)
    m = float(z.mean())
    v = float(((z - m) ** 2).mean() + 1e-12)
    k = float(((z - m) ** 4).mean() / (v ** 2))
    excess = k - 3.0
    return -excess

def two_halves_gap(z_1d: np.ndarray) -> float:
    z = np.sort(np.asarray(z_1d, dtype=float))
    N = len(z)
    left = z[: N // 2]
    right = z[N // 2 :]
    return float(right.mean() - left.mean())


