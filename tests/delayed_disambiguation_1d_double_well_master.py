def main(cfg: Config) -> None:
    out_dir = _ensure_dir(cfg)

    # extras dict passed into generator + PF
    extras = dict(
        a=cfg.a,
        lam=cfg.lam,
        dt=cfg.dt,
        process_noise=cfg.process_noise,
        emit_noise=cfg.emit_noise,
        emission_mode=cfg.emission_mode,
        eps=cfg.eps,
        n_even=cfg.n_even,
        k_tanh=cfg.k_tanh,
    )

    # Save config upfront
    _write_json(out_dir, "config.json", {"cfg": asdict(cfg), "extras": extras})

    # Build stationary generator objects
    prior = GaussianPrior(mu0=np.zeros(cfg.dz), cov0=np.eye(cfg.dz))
    transition = GaussianTransition(mean_fn=trans_mean_potential, cov_fn=trans_cov_isotropic)
    emission = GaussianEmission(mean_fn=emit_mean, cov_fn=emit_cov_isotropic)

    # Generate one trajectory
    batch = generate_sequences(
        T=cfg.T,
        B=cfg.B,
        prior=prior,
        transition=transition,
        emission=emission,
        seed=cfg.seed_data,
        return_logp=False,
        extras=extras,
    )
    x = batch.x[0]        # (T,2)
    z_true = batch.z[0]   # (T,1)

    # Run PF
    pf = bootstrap_pf(
        x_seq=x,
        prior=prior,
        transition=transition,
        emission=emission,
        N=cfg.N,
        seed=cfg.seed_pf,
        extras=extras,
        resample_every=cfg.resample_every,
    )

    # ------------------------------------------------------------
    # Plots
    # ------------------------------------------------------------

    if cfg.do_observation_plots:
        fig = plt.figure(figsize=(10, 3))
        plt.plot(np.arange(1, cfg.T + 1), x[:, 0], label="x1=z^2 + noise")
        plt.plot(np.arange(1, cfg.T + 1), x[:, 1], label=f"x2 ({cfg.emission_mode})")
        plt.xlabel("t")
        plt.title("Observation channels (sanity)")
        plt.grid(True)
        plt.legend()
        _savefig(out_dir, "observations_timeseries.png", fig)

        fig = plt.figure(figsize=(5, 5))
        plt.scatter(z_true[:, 0], x[:, 1], s=10)
        plt.xlabel("z_true")
        plt.ylabel("x2")
        plt.title("Emission sanity: x2 vs z_true")
        plt.grid(True)
        _savefig(out_dir, "emission_x2_vs_z.png", fig)

    if cfg.do_heatmaps:
        Hpred, zgrid_pred = predictive_heatmap(
            pf, nbins=cfg.heatmap_bins, p_lo=cfg.heatmap_zclip_lo, p_hi=cfg.heatmap_zclip_hi
        )
        fig = plt.figure(figsize=(11, 4))
        plt.imshow(
            Hpred,
            aspect="auto",
            origin="lower",
            extent=[zgrid_pred[0], zgrid_pred[-1], 1, cfg.T - 1],
            interpolation="nearest",
        )
        plt.colorbar(label="density (hist)")
        plt.plot(z_true[1:, 0], np.arange(1, cfg.T), linewidth=2)
        plt.xlabel("z")
        plt.ylabel("t")
        plt.title("Predictive heatmap: p(z_t | x_{<t}) + true z_t")
        plt.grid(False)
        _savefig(out_dir, "heatmap_predictive.png", fig)

        Hfilt, zgrid_filt = filtering_heatmap(
            pf, nbins=cfg.heatmap_bins, p_lo=cfg.heatmap_zclip_lo, p_hi=cfg.heatmap_zclip_hi
        )
        fig = plt.figure(figsize=(11, 4))
        plt.imshow(
            Hfilt,
            aspect="auto",
            origin="lower",
            extent=[zgrid_filt[0], zgrid_filt[-1], 1, cfg.T],
            interpolation="nearest",
        )
        plt.colorbar(label="density (weighted hist)")
        plt.plot(z_true[:, 0], np.arange(1, cfg.T + 1), linewidth=2)
        plt.xlabel("z")
        plt.ylabel("t")
        plt.title("Filtering heatmap: p(z_t | x_{<=t}) + true z_t")
        plt.grid(False)
        _savefig(out_dir, "heatmap_filtering.png", fig)

    if cfg.do_ess:
        fig = plt.figure(figsize=(10, 3))
        plt.plot(np.arange(1, cfg.T + 1), pf.ess)
        plt.xlabel("t")
        plt.ylabel("ESS")
        plt.title("ESS after weighting with x_t")
        plt.grid(True)
        _savefig(out_dir, "ess_curve.png", fig)

    mleft_pred, mleft_filt = branch_mass_curves(pf)

    if cfg.do_branch_mass:
        fig = plt.figure(figsize=(10, 3))
        plt.plot(np.arange(1, cfg.T + 1), mleft_pred, label="P(z_t<0 | x_{<t}) (predictive)")
        plt.plot(np.arange(1, cfg.T + 1), mleft_filt, label="P(z_t<0 | x_{<=t}) (filtering)")
        plt.axhline(cfg.left_thresh, linestyle="--", label=f"thresh={cfg.left_thresh:g}")
        plt.xlabel("t")
        plt.ylabel("left-branch mass")
        plt.title("Branch-mass curves")
        plt.grid(True)
        plt.legend()
        _savefig(out_dir, "branch_mass_curves.png", fig)

        fig = plt.figure(figsize=(10, 3))
        plt.plot(np.arange(1, cfg.T + 1), pf.log_odds_pred, label="log-odds (predictive)")
        plt.plot(np.arange(1, cfg.T + 1), pf.log_odds_filt, label="log-odds (filtering)")
        plt.xlabel("t")
        plt.ylabel("log((1-m)/m)")
        plt.title("Log-odds from branch masses (proxy for likelihood-ratio accumulation)")
        plt.grid(True)
        plt.legend()
        _savefig(out_dir, "branch_log_odds.png", fig)

    if cfg.do_evidence:
        fig = plt.figure(figsize=(10, 3))
        plt.plot(np.arange(1, cfg.T + 1), pf.log_evidence)
        plt.xlabel("t")
        plt.ylabel("log p(x_t | x_{<t})")
        plt.title("Per-step log evidence increment (PF approximation)")
        plt.grid(True)
        _savefig(out_dir, "log_evidence_per_step.png", fig)

        fig = plt.figure(figsize=(10, 3))
        plt.plot(np.arange(1, cfg.T + 1), pf.cum_log_evidence)
        plt.xlabel("t")
        plt.ylabel("Σ log p(x_s | x_{<s})")
        plt.title("Cumulative log evidence (evidence accumulation)")
        plt.grid(True)
        _savefig(out_dir, "log_evidence_cumulative.png", fig)

    # ------------------------------------------------------------
    # Forecast divergence (mixture vs forced-right) at t_star
    # ------------------------------------------------------------
    forecast_div = None
    if cfg.do_forecast_divergence:
        t_idx = max(1, min(cfg.T, int(cfg.t_star))) - 1  # 0-based
        zt = pf.z_filt[t_idx]
        wt = pf.w_filt[t_idx]

        mix = rollout_forecast_from_particles(
            zt, wt, transition, emission, extras, H=cfg.H_forecast, seed=999, resample_by_weights=True
        )

        mask_right = (zt[:, 0] >= 0.0)
        z_right = zt[mask_right]
        w_right = wt[mask_right]
        if z_right.shape[0] < 25:
            # if branch basically dead, don't crash
            z_right, w_right = zt, wt

        right = rollout_forecast_from_particles(
            z_right, w_right, transition, emission, extras, H=cfg.H_forecast, seed=1001, resample_by_weights=True
        )

        hgrid = np.arange(1, cfg.H_forecast + 1)

        # focus on x2 because it is the "sign channel" in these synthetics
        fig = plt.figure(figsize=(10, 3))
        plt.plot(hgrid, mix["mean"][:, 1], label="mixture forecast mean (x2)")
        plt.plot(hgrid, right["mean"][:, 1], label="forced-right forecast mean (x2)")
        plt.xlabel("horizon h")
        plt.ylabel("E[x2_{t*+h}]")
        plt.title(f"Forecast divergence at t*={cfg.t_star}: mixture vs forced-right")
        plt.grid(True)
        plt.legend()
        _savefig(out_dir, "forecast_divergence_x2_mean.png", fig)

        forecast_div = float(np.sqrt(np.mean((mix["mean"][:, 1] - right["mean"][:, 1]) ** 2)))

    # ------------------------------------------------------------
    # Sensitivity sweeps
    # ------------------------------------------------------------
    resample_results = None
    N_results = None

    if cfg.do_sensitivity:
        # collapse times vs resample_every
        resample_results = []
        for re in cfg.resample_grid:
            pf_re = bootstrap_pf(
                x_seq=x,
                prior=prior,
                transition=transition,
                emission=emission,
                N=cfg.N,
                seed=cfg.seed_pf,
                extras=extras,
                resample_every=int(re),
            )
            _, mleft_f = branch_mass_curves(pf_re)
            c = collapse_time(mleft_f, cfg.left_thresh)
            resample_results.append((int(re), -1 if c is None else int(c)))

        fig = plt.figure(figsize=(8, 3))
        plt.plot([r for r, _ in resample_results], [c for _, c in resample_results], marker="o")
        plt.xlabel("resample_every (0 = never)")
        plt.ylabel(f"collapse time (t where left-mass<{cfg.left_thresh:g})")
        plt.title("Collapse-time sensitivity to resampling frequency")
        plt.grid(True)
        _savefig(out_dir, "sensitivity_resample_every.png", fig)

        # collapse times vs N
        N_results = []
        for N in cfg.N_grid:
            pf_N = bootstrap_pf(
                x_seq=x,
                prior=prior,
                transition=transition,
                emission=emission,
                N=int(N),
                seed=cfg.seed_pf,
                extras=extras,
                resample_every=cfg.resample_every,
            )
            _, mleft_f = branch_mass_curves(pf_N)
            c = collapse_time(mleft_f, cfg.left_thresh)
            N_results.append((int(N), -1 if c is None else int(c)))

        fig = plt.figure(figsize=(8, 3))
        plt.plot([n for n, _ in N_results], [c for _, c in N_results], marker="o")
        plt.xlabel("N particles")
        plt.ylabel(f"collapse time (t where left-mass<{cfg.left_thresh:g})")
        plt.title("Collapse-time sensitivity to particle count")
        plt.grid(True)
        _savefig(out_dir, "sensitivity_particle_count.png", fig)

    # ------------------------------------------------------------
    # Optional “cheap” diagnostics (fast): kurtosis + gap on predictive particles
    # (kept separate from dip/silverman heavy tests)
    # ------------------------------------------------------------
    diag = {}
    if cfg.do_diagnostics:
        # Note: this is still relatively cheap; the heavy tests are not included here.
        # We compute on predictive p(z_t|x_{<t}) using z_pred[t-1].
        kurt = []
        gap = []
        for t in range(1, cfg.T):
            zpt = pf.z_pred[t - 1][:, 0]
            # subsample for speed
            if zpt.size > 5000:
                idx = np.random.default_rng(0).choice(zpt.size, size=5000, replace=False)
                zpt = zpt[idx]
            kurt.append(bimodality_kurtosis_proxy(zpt))
            gap.append(two_halves_gap(zpt))

        diag["kurtosis_proxy"] = np.asarray(kurt, dtype=float)
        diag["gap_proxy"] = np.asarray(gap, dtype=float)

        tgrid = np.arange(1, cfg.T)
        fig = plt.figure(figsize=(10, 3))
        plt.plot(tgrid, diag["kurtosis_proxy"])
        plt.xlabel("t")
        plt.ylabel("-excess kurtosis (predictive)")
        plt.title("Predictive shape proxy vs time")
        plt.grid(True)
        _savefig(out_dir, "diagnostic_kurtosis_proxy.png", fig)

        fig = plt.figure(figsize=(10, 3))
        plt.plot(tgrid, diag["gap_proxy"])
        plt.xlabel("t")
        plt.ylabel("two-halves gap (predictive)")
        plt.title("Predictive separation proxy vs time")
        plt.grid(True)
        _savefig(out_dir, "diagnostic_gap_proxy.png", fig)

    # ------------------------------------------------------------
    # Save arrays + summary
    # ------------------------------------------------------------
    collapse_pred = collapse_time(mleft_pred, cfg.left_thresh)
    collapse_filt = collapse_time(mleft_filt, cfg.left_thresh)

    np.savez(
        out_dir / "results.npz",
        z_true=z_true,
        x=x,
        ess=pf.ess,
        log_evidence=pf.log_evidence,
        cum_log_evidence=pf.cum_log_evidence,
        log_odds_pred=pf.log_odds_pred,
        log_odds_filt=pf.log_odds_filt,
        mleft_pred=mleft_pred,
        mleft_filt=mleft_filt,
        collapse_pred_t=-1 if collapse_pred is None else int(collapse_pred),
        collapse_filt_t=-1 if collapse_filt is None else int(collapse_filt),
        forecast_divergence_x2_mean_l2=(-1.0 if forecast_div is None else float(forecast_div)),
        resample_results=(np.array(resample_results, dtype=float) if resample_results is not None else np.zeros((0, 2))),
        N_results=(np.array(N_results, dtype=float) if N_results is not None else np.zeros((0, 2))),
        # optional diagnostics
        kurtosis_proxy=(diag.get("kurtosis_proxy", np.zeros((0,), dtype=float))),
        gap_proxy=(diag.get("gap_proxy", np.zeros((0,), dtype=float))),
    )

    summary_lines = [
        f"out_dir = {out_dir.resolve()}",
        "",
        "Key readouts:",
        f"  collapse_pred_t (mleft_pred < {cfg.left_thresh:g}) = {collapse_pred}",
        f"  collapse_filt_t (mleft_filt < {cfg.left_thresh:g}) = {collapse_filt}",
    ]
    if forecast_div is not None:
        summary_lines.append(f"  forecast_divergence_x2_mean_l2 @ t*={cfg.t_star}, H={cfg.H_forecast} = {forecast_div:.6f}")
    summary_lines += [
        "",
        "Interpretation tips (what each plot is telling you):",
        "  heatmap_predictive.png:",
        "    - Row t shows p(z_t | x_{<t}) (what you believe *before* seeing x_t).",
        "    - Two bumps early -> genuine ambiguity; collapse later -> disambiguation by evidence.",
        "  heatmap_filtering.png:",
        "    - Row t shows p(z_t | x_{<=t}) (after assimilating x_t).",
        "  ess_curve.png:",
        "    - ESS drops indicate evidence concentrates weight on fewer hypotheses.",
        "  branch_mass_curves.png:",
        "    - Tracks how probability mass migrates from left to right branch (or vice versa).",
        "  log_evidence_per_step.png / log_evidence_cumulative.png:",
        "    - PF approximation of evidence accumulation: log p(x_t|x_{<t}) and cumulative sum.",
        "  branch_log_odds.png:",
        "    - log((1-m)/m) is a simple *odds* proxy; monotone growth indicates accumulating support.",
        "  forecast_divergence_x2_mean.png:",
        "    - If mixture vs forced-branch forecasts differ materially, then ‘keeping both’ matters for forecasting.",
        "",
        "If you don’t see two peaks in predictive heatmap:",
        "  - Usually means the emission is too informative too early (eps too large),",
        "    or dynamics cross the informative region too frequently (dt/lam too high),",
        "    or process_noise is too high (smears modes).",
        "",
    ]
    (out_dir / "summary.txt").write_text("\n".join(summary_lines))

    print("\n".join(summary_lines))


def parse_args() -> Config:
    p = argparse.ArgumentParser()
    # core
    p.add_argument("--T", type=int, default=90)
    p.add_argument("--seed-data", type=int, default=0)
    p.add_argument("--seed-pf", type=int, default=123)
    p.add_argument("--N", type=int, default=30000)
    p.add_argument("--resample-every", type=int, default=3)

    # well params
    p.add_argument("--a", type=float, default=1.0)
    p.add_argument("--lambda", dest="lam", type=float, default=1.0)
    p.add_argument("--dt", type=float, default=0.06)
    p.add_argument("--process-noise", type=float, default=0.18)

    # emission params
    p.add_argument("--emit-noise", type=float, default=0.20)
    p.add_argument("--emission-mode", type=str, default="gated_linear",
                   choices=["gated_linear", "band_evenpower", "tanh_saturate"])
    p.add_argument("--eps", type=float, default=0.50)
    p.add_argument("--n-even", type=int, default=2)
    p.add_argument("--k-tanh", type=float, default=2.5)

    # analysis toggles
    p.add_argument("--no-heatmaps", action="store_true")
    p.add_argument("--no-observations", action="store_true")
    p.add_argument("--no-branch-mass", action="store_true")
    p.add_argument("--no-ess", action="store_true")
    p.add_argument("--no-evidence", action="store_true")
    p.add_argument("--no-forecast", action="store_true")
    p.add_argument("--no-sensitivity", action="store_true")
    p.add_argument("--diagnostics", action="store_true")  # off by default

    # forecast
    p.add_argument("--t-star", type=int, default=55)
    p.add_argument("--H-forecast", type=int, default=20)

    # saving
    p.add_argument("--results-root", type=str, default="results")
    p.add_argument("--subfolder", type=str, default="_synthetic_1d_double_well_analysis")
    p.add_argument("--run-name", type=str, default="")

    args = p.parse_args()

    cfg = Config(
        T=args.T,
        seed_data=args.seed_data,
        seed_pf=args.seed_pf,
        N=args.N,
        resample_every=args.resample_every,
        a=args.a,
        lam=args.lam,
        dt=args.dt,
        process_noise=args.process_noise,
        emit_noise=args.emit_noise,
        emission_mode=args.emission_mode,
        eps=args.eps,
        n_even=args.n_even,
        k_tanh=args.k_tanh,
        do_heatmaps=(not args.no_heatmaps),
        do_observation_plots=(not args.no_observations),
        do_branch_mass=(not args.no_branch_mass),
        do_ess=(not args.no_ess),
        do_evidence=(not args.no_evidence),
        do_forecast_divergence=(not args.no_forecast),
        do_sensitivity=(not args.no_sensitivity),
        do_diagnostics=args.diagnostics,
        t_star=args.t_star,
        H_forecast=args.H_forecast,
        results_root=args.results_root,
        subfolder=args.subfolder,
        run_name=args.run_name,
    )
    return cfg


if __name__ == "__main__":
    cfg = parse_args()
    main(cfg)