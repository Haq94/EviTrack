def _hist_row(samples_1d: np.ndarray, edges: np.ndarray, weights: Optional[np.ndarray] = None) -> np.ndarray:
    if weights is None:
        h, _ = np.histogram(samples_1d, bins=edges, density=False)
        h = h.astype(float)
    else:
        w = weights / (weights.sum() + 1e-12)
        h, _ = np.histogram(samples_1d, bins=edges, weights=w, density=False)
        h = h.astype(float)
    h = h / (h.sum() + 1e-12)
    return h

def _auto_edges_from_particles(z_lists: List[np.ndarray], nbins: int, p_lo: float, p_hi: float) -> Tuple[np.ndarray, np.ndarray]:
    allz = np.concatenate([zz[:, 0] for zz in z_lists], axis=0)
    lo = float(np.percentile(allz, p_lo))
    hi = float(np.percentile(allz, p_hi))
    pad = 0.20 * (hi - lo + 1e-9)
    lo -= pad
    hi += pad
    edges = np.linspace(lo, hi, nbins + 1)
    centers = 0.5 * (edges[:-1] + edges[1:])
    return edges, centers

def predictive_heatmap(pf: PFOutputs, nbins: int, p_lo: float, p_hi: float) -> Tuple[np.ndarray, np.ndarray]:
    edges, centers = _auto_edges_from_particles(pf.z_pred, nbins, p_lo, p_hi)
    H = np.zeros((len(pf.z_pred), nbins), dtype=float)
    for t, zp in enumerate(pf.z_pred):
        H[t] = _hist_row(zp[:, 0], edges)
    return H, centers

def filtering_heatmap(pf: PFOutputs, nbins: int, p_lo: float, p_hi: float) -> Tuple[np.ndarray, np.ndarray]:
    edges, centers = _auto_edges_from_particles(pf.z_filt, nbins, p_lo, p_hi)
    H = np.zeros((len(pf.z_filt), nbins), dtype=float)
    for t, (zf, wf) in enumerate(zip(pf.z_filt, pf.w_filt)):
        H[t] = _hist_row(zf[:, 0], edges, weights=wf)
    return H, centers

def branch_mass_curves(pf: PFOutputs) -> Tuple[np.ndarray, np.ndarray]:
    """
    mleft_pred[t] = P(z_t<0 | x_{<t})  using log_odds_pred
    mleft_filt[t] = P(z_t<0 | x_{<=t}) using log_odds_filt
    """
    # log_odds = log((1-m)/m) => m = 1/(1+exp(log_odds))
    mleft_pred = 1.0 / (1.0 + np.exp(pf.log_odds_pred))
    mleft_filt = 1.0 / (1.0 + np.exp(pf.log_odds_filt))
    return mleft_pred, mleft_filt

def collapse_time(mleft: np.ndarray, thresh: float) -> Optional[int]:
    """
    First t (1-based) where mleft < thresh and stays there.
    """
    below = (mleft < thresh)
    if not np.any(below):
        return None
    for i in range(len(mleft)):
        if below[i] and np.all(below[i:]):
            return i + 1
    return int(np.argmax(below)) + 1

def rollout_forecast_from_particles(
    z_particles: np.ndarray,             # (N,1)
    weights: Optional[np.ndarray],       # (N,) or None
    transition: GaussianTransition,
    emission: GaussianEmission,
    extras: Dict,
    *,
    H: int,
    seed: int,
    resample_by_weights: bool = True,
) -> Dict[str, np.ndarray]:
    rng = np.random.default_rng(seed)
    z = z_particles.copy()
    N = z.shape[0]
    dz = z.shape[1]

    if weights is not None and resample_by_weights:
        w = weights / (weights.sum() + 1e-12)
        idx = rng.choice(N, size=N, replace=True, p=w)
        z = z[idx]

    xs = []
    for _h in range(H):
        # z -> z_next
        mu_z = np.asarray(transition.mean_fn(z, extras), dtype=float)
        cov_z = np.asarray(transition.cov_fn(z, extras), dtype=float)
        if cov_z.ndim == 2:
            cov_z = np.broadcast_to(cov_z, (N, dz, dz))
        z_next = np.empty_like(z)
        for i in range(N):
            z_next[i] = rng.multivariate_normal(mean=mu_z[i], cov=cov_z[i])
        z = z_next

        # x | z
        mu_x = np.asarray(emission.mean_fn(z, extras), dtype=float)  # (N,2)
        cov_x = np.asarray(emission.cov_fn(z, extras), dtype=float)  # (2,2) or (N,2,2)
        if cov_x.ndim == 2:
            cov_x = np.broadcast_to(cov_x, (N, 2, 2))
        x_next = np.empty((N, 2), dtype=float)
        for i in range(N):
            x_next[i] = rng.multivariate_normal(mean=mu_x[i], cov=cov_x[i])
        xs.append(x_next)

    X = np.stack(xs, axis=1)  # (N,H,2)
    return {"X": X, "mean": X.mean(axis=0), "var": X.var(axis=0)}


