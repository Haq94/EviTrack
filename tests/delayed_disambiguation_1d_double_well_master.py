def _savefig(out_dir: Path, name: str, fig: plt.Figure, dpi: int = 200) -> None:
    fig.savefig(out_dir / name, dpi=dpi, bbox_inches="tight")
    plt.close(fig)

def _write_json(out_dir: Path, name: str, obj: Dict) -> None:
    (out_dir / name).write_text(json.dumps(obj, indent=2))

def _ensure_dir(cfg: Config) -> Path:
    root = Path(cfg.results_root) / cfg.subfolder
    root.mkdir(parents=True, exist_ok=True)
    run = cfg.run_name.strip() or _autoname(cfg)
    out_dir = root / run
    out_dir.mkdir(parents=True, exist_ok=True)
    return out_dir


